#!/bin/sh
# Embeds packages/bot-avatar/fixtures/catalog.json (the bot parts catalog, the single source of truth) verbatim in
# Sources/CapcomdBot/CatalogJSON.swift. Run it after `bun packages/bot-avatar/scripts/golden.ts` changes the catalog;
# CapcomdBotTests fails while the embedded copy differs from the package file.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)
src="$here/../../../packages/bot-avatar/fixtures/catalog.json"
out="$here/Sources/CapcomdBot/CatalogJSON.swift"
# The copy is a raw string literal (##"""…"""##): it must not contain its own terminator or escape.
if grep -q -e '"""##' -e '\\##' "$src"; then echo "catalog.json contains \"\"\"## or \\##; change the delimiter" >&2; exit 1; fi
{
  echo "// Generated by scripts/gen-bot-catalog.sh from packages/bot-avatar/fixtures/catalog.json. Do not edit."
  echo "// The string is the file byte for byte (CatalogTests checks it)."
  echo 'let catalogJSON = ##"""'
  cat "$src"
  echo
  echo '"""##'
} > "$out"
echo "wrote $out"
