#!/usr/bin/env bun
// Build capcomd as a single executable: dist/capcomd-<os>-<arch>, and its .sha256. It carries the CLI, the files it
// needs while it runs (src/utils/assets.ts), rivetkit's native addon and rivet-engine for that platform (the engine
// is extracted to ~/.capcomd/bin/<version>/ on first `serve`). Any target builds on any host: the target's native
// packages come from npm, at the versions installed here, checked against the registry's integrity hash.
//   bun scripts/build-binary.ts [--target darwin-arm64|darwin-x64|linux-x64|linux-arm64] [--outdir dist]
import { createHash } from "crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from "fs";
import { join, resolve } from "path";

export const TARGETS = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64"] as const;
export type Target = (typeof TARGETS)[number];

const root = resolve(import.meta.dir, "..");
const arg = (k: string) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : undefined; };

/** The npm packages that hold a target's native parts (rivetkit's own names: the engine is musl-static on Linux). */
export function platformPackages(t: Target): { napi: string; engine: string } {
  const linux = t.startsWith("linux-");
  return { napi: `@rivetkit/rivetkit-napi-${linux ? `${t}-gnu` : t}`, engine: `@rivetkit/engine-cli-${linux ? `${t}-musl` : t}` };
}

/** Bun's compile target: x64 Linux uses the baseline build, which runs on CPUs without AVX2 too. */
export const bunTarget = (t: Target) => (t === "linux-x64" ? "bun-linux-x64-baseline" : `bun-${t}`) as Bun.Build.CompileTarget;

const versionOf = (pkg: string) => JSON.parse(readFileSync(join(root, "node_modules", pkg, "package.json"), "utf8")).version as string;

/** A package's directory: node_modules when installed (the host's own platform), else fetched from npm and verified. */
async function packageDir(name: string, version: string): Promise<string> {
  const local = join(root, "node_modules", name);
  if (existsSync(join(local, "package.json")) && JSON.parse(readFileSync(join(local, "package.json"), "utf8")).version === version) return local;
  const dir = join(root, "dist", ".platform", `${name.replace("/", "__")}@${version}`);
  if (existsSync(join(dir, "package", "package.json"))) return join(dir, "package");
  const meta = await (await fetch(`https://registry.npmjs.org/${name}/${version}`)).json() as { dist: { tarball: string; integrity: string } };
  const tgz = Buffer.from(await (await fetch(meta.dist.tarball)).arrayBuffer());
  const [algo, want] = meta.dist.integrity.split("-", 2) as [string, string];
  const got = createHash(algo).update(tgz).digest("base64");
  if (got !== want) throw new Error(`${name}@${version}: integrity mismatch (registry ${meta.dist.integrity}, downloaded ${algo}-${got})`);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "pkg.tgz"), tgz);
  const r = Bun.spawnSync(["tar", "-xzf", "pkg.tgz"], { cwd: dir });
  if (r.exitCode !== 0) throw new Error(`${name}: tar failed: ${r.stderr}`);
  return join(dir, "package");
}

export async function build(target: Target, outdir: string): Promise<string> {
  const pk = platformPackages(target);
  const napiDir = await packageDir(pk.napi, versionOf("@rivetkit/rivetkit-napi"));
  const engineDir = await packageDir(pk.engine, versionOf("@rivetkit/engine-cli"));
  const napiMain = join(napiDir, JSON.parse(readFileSync(join(napiDir, "package.json"), "utf8")).main);
  const engine = join(engineDir, "rivet-engine");
  for (const f of [napiMain, engine]) if (!existsSync(f)) throw new Error(`missing ${f}`);

  const name = `capcomd-${target}`;
  mkdirSync(outdir, { recursive: true });
  // The entry hands the bundled engine to the CLI before the CLI runs (a dynamic import keeps that order).
  const entry = join(root, "src", `.entry-${name}.ts`);
  writeFileSync(entry, `// generated by scripts/build-binary.ts
import engine from ${JSON.stringify(engine)} with { type: "file" };
import { embedded } from "./utils/assets";
embedded.engine = engine;
await import("./cli/index.ts");
`);
  // rivetkit builds some package names at run time (["@rivetkit", "rivetkit-napi"].join("/")) so bundlers skip them.
  // Spelled out, the bundler embeds them: its native runtime, and the engine resolver, which finds the engine
  // through RIVET_ENGINE_BINARY (set by `serve` to the extracted engine's launcher).
  const COMPUTED = /(import|require)\(\["@rivetkit", "(rivetkit-napi|engine-cli)"\]\.join\("\/"\)\)/g;
  const rewrites = new Set<string>();
  const rivetkit: import("bun").BunPlugin = {
    name: "rivetkit-platform",
    setup(b) {
      b.onLoad({ filter: /node_modules\/rivetkit\/dist\/.*\.c?js$/ }, async (a) => {
        const src = await Bun.file(a.path).text();
        return { contents: src.replace(COMPUTED, (_m, fn, pkg) => { rewrites.add(pkg); return `${fn}("@rivetkit/${pkg}")`; }), loader: "js" };
      });
      // The target's native addon; every other platform's package stays out (it is only required on that platform).
      b.onResolve({ filter: /^@rivetkit\/(rivetkit-napi|engine-cli)-/ }, (a) =>
        a.path === pk.napi ? { path: napiMain } : { path: a.path, external: true });
    },
  };
  const out = join(outdir, name);
  try {
    const r = await Bun.build({
      entrypoints: [entry],
      plugins: [rivetkit],
      // Never pick up a .env or bunfig.toml from wherever capcomd is run (a user's repository).
      compile: { target: bunTarget(target), outfile: out, autoloadDotenv: false, autoloadBunfig: false },
    });
    if (!r.success) { for (const l of r.logs) console.error(l); throw new Error("bun build --compile failed"); }
    for (const p of ["rivetkit-napi", "engine-cli"]) if (!rewrites.has(p)) throw new Error(`rivetkit's import of @rivetkit/${p} wasn't found, so the binary couldn't run the engine (did rivetkit change?)`);
  } finally {
    rmSync(entry, { force: true });
  }
  const sha = createHash("sha256").update(readFileSync(out)).digest("hex");
  writeFileSync(`${out}.sha256`, `${sha}  ${name}\n`);
  console.log(`${out} (${(statSync(out).size / 1e6).toFixed(0)} MB) sha256 ${sha}`);
  return out;
}

if (import.meta.main) {
  const host = `${process.platform}-${process.arch}`;
  const target = (arg("--target") ?? host) as Target;
  if (!TARGETS.includes(target)) throw new Error(`no single-executable build for ${target} (targets: ${TARGETS.join(", ")})`);
  await build(target, resolve(arg("--outdir") ?? join(root, "dist")));
}
