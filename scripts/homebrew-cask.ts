#!/usr/bin/env bun
// The Homebrew cask for a release's app (MarvinAmador7/homebrew-tap, Casks/capcomd-app.rb), from the .sha256 file
// apps/menubar/scripts/build-app.sh --zip wrote. The release workflow commits it to the tap next to the formula.
//   bun scripts/homebrew-cask.ts 0.10.0 apps/menubar/build > capcomd-app.rb
//   bun scripts/homebrew-cask.ts 0.10.0 dir file:///…/dir capcomd-ci/test/capcomd   (a throwaway tap, before a release)
//
// It's named capcomd-app, not capcomd: the tap's formula is capcomd (the CLI), and a cask of the same name in the same
// tap makes `brew install MarvinAmador7/tap/capcomd` ambiguous (brew picks the formula and says so). The cask depends
// on the formula, so `brew install --cask MarvinAmador7/tap/capcomd-app` installs both.
import { readFileSync } from "fs";
import { join } from "path";

const REPO = "MarvinAmador7/capcomd";
export const CASK = "capcomd-app";
export const BUNDLE_ID = "dev.capcomd.app";
export const zipName = (version: string) => `capcomd-app-${version}.zip`;

/** `base`: where the zip is (the release; a file:// directory to test the cask before one exists). `formula`: the CLI's
 *  formula, by its full name (the tap's own unless testing). */
export function cask(version: string, sha256: string, o: { base?: string; formula?: string } = {}): string {
  const url = o.base ? `"${o.base}/${zipName(version)}"` : `"https://github.com/${REPO}/releases/download/v#{version}/capcomd-app-#{version}.zip"`;
  return `# Generated by scripts/homebrew-cask.ts in ${REPO} for each release; edits here are overwritten.
cask "${CASK}" do
  version "${version}"
  sha256 "${sha256}"

  url ${url}
  name "capcomd"
  desc "Window and menu bar app for the capcomd agent orchestrator"
  homepage "https://github.com/${REPO}"

  depends_on macos: ">= :sonoma"
  depends_on formula: "${o.formula ?? "marvinamador7/tap/capcomd"}"

  app "capcomd.app"

  uninstall quit: "${BUNDLE_ID}"

  zap trash: [
    "~/Library/Caches/${BUNDLE_ID}",
    "~/Library/HTTPStorages/${BUNDLE_ID}",
    "~/Library/Preferences/${BUNDLE_ID}.plist",
    "~/Library/Saved Application State/${BUNDLE_ID}.savedState",
  ]

  # Until the app is notarized (it's signed ad hoc), macOS blocks its first open.
  caveats <<~EOS
    capcomd.app isn't notarized by Apple yet, so macOS blocks it the first time you open it:
      1. Open capcomd from Applications. When macOS says it can't verify it, click Done.
      2. Open System Settings > Privacy & Security, scroll down and click Open Anyway next to "capcomd".
      3. Confirm with your password or Touch ID, and click Open Anyway again.
    After that it opens normally. It starts capcomd and connects to it by itself.
  EOS
end
`;
}

if (import.meta.main) {
  const [version, dir, base, formula] = process.argv.slice(2);
  if (!version || !dir) throw new Error("usage: bun scripts/homebrew-cask.ts <version> <dir with capcomd-app-<version>.zip.sha256> [<base url>] [<formula>]");
  const v = version.replace(/^v/, "");
  const sha = readFileSync(join(dir, `${zipName(v)}.sha256`), "utf8").trim().split(/\s+/)[0]!;
  if (!/^[0-9a-f]{64}$/.test(sha)) throw new Error(`no SHA-256 in ${join(dir, `${zipName(v)}.sha256`)}`);
  process.stdout.write(cask(v, sha, { ...(base ? { base } : {}), ...(formula ? { formula } : {}) }));
}
