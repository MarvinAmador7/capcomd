#!/usr/bin/env bun
// The Homebrew formula for a release's binaries (MarvinAmador7/homebrew-tap, Formula/capcomd.rb), from the
// .sha256 files scripts/build-binary.ts wrote. The release workflow commits it to the tap.
//   bun scripts/homebrew-formula.ts 0.6.0 dist > capcomd.rb
import { readFileSync } from "fs";
import { join } from "path";

const REPO = "MarvinAmador7/capcomd";

/** `base`: where the binaries are (the release; a file:// directory to test the formula before one exists). */
export function formula(version: string, sha: Record<"darwin-arm64" | "darwin-x64" | "linux-x64" | "linux-arm64", string>, base = `https://github.com/${REPO}/releases/download/v${version}`): string {
  const url = (t: string) => `${base}/capcomd-${t}`;
  const block = (t: keyof typeof sha) => `      url "${url(t)}"\n      sha256 "${sha[t]}"`;
  return `# Generated by scripts/homebrew-formula.ts in ${REPO} for each release; edits here are overwritten.
class Capcomd < Formula
  desc "Orchestrate Claude Code and Codex agents in isolated VMs"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${block("darwin-arm64")}
    end
    on_intel do
${block("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
${block("linux-arm64")}
    end
    on_intel do
${block("linux-x64")}
    end
  end

  def install
    bin.install Dir["capcomd-*"].first => "capcomd"
    chmod 0755, bin/"capcomd"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/capcomd --version")
  end
end
`;
}

if (import.meta.main) {
  const [version, dir, base] = process.argv.slice(2);
  if (!version || !dir) throw new Error("usage: bun scripts/homebrew-formula.ts <version> <dir with capcomd-*.sha256> [<base url>]");
  const sha = (t: string) => readFileSync(join(dir, `capcomd-${t}.sha256`), "utf8").trim().split(/\s+/)[0]!;
  process.stdout.write(formula(version.replace(/^v/, ""), { "darwin-arm64": sha("darwin-arm64"), "darwin-x64": sha("darwin-x64"), "linux-x64": sha("linux-x64"), "linux-arm64": sha("linux-arm64") }, base));
}
