// Vendors packages/bot-avatar (the deterministic pixel-bot engine) into lib/vendor as one ESM file, so the site
// builds on its own without joining a root workspace. Re-run after the engine changes: `bun run vendor`.
import { join } from "node:path";

const root = join(import.meta.dir, "..", "..");
const out = await Bun.build({ entrypoints: [join(root, "packages", "bot-avatar", "src", "index.ts")], target: "browser", format: "esm", minify: true });
if (!out.success) { console.error(out.logs); process.exit(1); }
const header = "// Generated by site/scripts/vendor-bot-avatar.ts from packages/bot-avatar. Do not edit; run `bun run vendor`.\n";
await Bun.write(join(import.meta.dir, "..", "lib", "vendor", "bot-avatar.js"), header + (await out.outputs[0]!.text()));
console.log("vendored packages/bot-avatar → site/lib/vendor/bot-avatar.js");
